from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np


@dataclass
class ColoredMesh:
    vertices: np.ndarray
    faces: np.ndarray
    vertex_colors: np.ndarray | None


def _index(token: str, vertex_count: int) -> int:
    value = int(token.split("/", 1)[0])
    return value - 1 if value > 0 else vertex_count + value


def _load_mtl(path: Path) -> dict[str, np.ndarray]:
    materials: dict[str, np.ndarray] = {}
    if not path.exists():
        return materials
    current = None
    with path.open("r", encoding="utf-8", errors="ignore") as handle:
        for line in handle:
            parts = line.strip().split()
            if not parts:
                continue
            if parts[0] == "newmtl" and len(parts) >= 2:
                current = parts[1]
            elif parts[0] == "Kd" and current is not None and len(parts) >= 4:
                materials[current] = np.asarray([float(parts[1]), float(parts[2]), float(parts[3])], dtype=np.float32)
    return materials


def load_colored_obj(path: str | Path) -> ColoredMesh:
    path = Path(path)
    vertices: list[list[float]] = []
    colors: list[list[float] | None] = []
    faces: list[list[int]] = []
    face_materials: list[str | None] = []
    material_file: str | None = None
    current_material: str | None = None
    with path.open("r", encoding="utf-8", errors="ignore") as handle:
        for line in handle:
            parts = line.strip().split()
            if not parts or parts[0].startswith("#"):
                continue
            if parts[0] == "mtllib" and len(parts) >= 2:
                material_file = parts[1]
            elif parts[0] == "usemtl" and len(parts) >= 2:
                current_material = parts[1]
            elif parts[0] == "v" and len(parts) >= 4:
                vertices.append([float(parts[1]), float(parts[2]), float(parts[3])])
                colors.append([float(parts[4]), float(parts[5]), float(parts[6])] if len(parts) >= 7 else None)
            elif parts[0] == "f" and len(parts) >= 4:
                polygon = [_index(token, len(vertices)) for token in parts[1:]]
                for triangle_index in range(1, len(polygon) - 1):
                    faces.append([polygon[0], polygon[triangle_index], polygon[triangle_index + 1]])
                    face_materials.append(current_material)

    if not vertices or not faces:
        raise ValueError(f"Colored OBJ must contain vertices and faces: {path}")
    vertices_array = np.asarray(vertices, dtype=np.float32)
    faces_array = np.asarray(faces, dtype=np.int64)
    vertex_colors: np.ndarray | None = None
    if all(color is not None for color in colors):
        vertex_colors = np.asarray(colors, dtype=np.float32)
    elif material_file:
        materials = _load_mtl(path.parent / material_file)
        accumulated = np.zeros((len(vertices_array), 3), dtype=np.float32)
        counts = np.zeros(len(vertices_array), dtype=np.float32)
        for face, material_name in zip(faces_array, face_materials):
            if material_name not in materials:
                continue
            accumulated[face] += materials[material_name]
            counts[face] += 1.0
        if np.any(counts > 0):
            vertex_colors = accumulated / np.maximum(counts[:, None], 1.0)
            missing = counts == 0
            if np.any(missing):
                vertex_colors[missing] = np.nan
    if vertex_colors is None or not np.all(np.isfinite(vertex_colors)):
        raise ValueError(
            f"No complete vertex/material colors found in {path}. "
            "Provide vertex colors, an MTL, or a custom converter."
        )
    return ColoredMesh(vertices_array, faces_array, vertex_colors)


def write_uncolored_obj(path: str | Path, vertices: np.ndarray, faces: np.ndarray) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("# Generated by rotomolding_ai; vertex colors removed.\n")
        for vertex in vertices:
            handle.write(f"v {vertex[0]:.8f} {vertex[1]:.8f} {vertex[2]:.8f}\n")
        for face in faces:
            handle.write(f"f {face[0] + 1} {face[1] + 1} {face[2] + 1}\n")
